create table if not exists public.verum_entries (
  id bigint generated by default as identity primary key,
  day date not null unique,
  text text not null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.verum_quotes (
  id bigint generated by default as identity primary key,
  text text not null,
  author text not null default '',
  score int not null default 0,
  last_seen_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (text, author)
);

create table if not exists public.verum_quotes_daily_pick (
  day date primary key,
  quote_id bigint not null references public.verum_quotes(id) on delete cascade,
  picked_at timestamptz not null default now()
);

-- RLS on, no policies: the anon key can do nothing; all access goes through
-- the service-role key from server-side API routes.
alter table public.verum_entries enable row level security;
alter table public.verum_quotes enable row level security;
alter table public.verum_quotes_daily_pick enable row level security;

-- Atomic daily-quote pick: choose a quote for p_day (preferring "core"
-- quotes not seen within p_avoid_days), record it, and return it. Once a
-- pick exists for the day, every later call returns the same quote.
create or replace function public.verum_pick_daily_quote(
  p_day date,
  p_core_threshold int,
  p_avoid_days int
) returns setof public.verum_quotes
language plpgsql
as $$
declare
  v_id bigint;
begin
  select quote_id into v_id
  from public.verum_quotes_daily_pick
  where day = p_day;

  if v_id is null then
    -- Core quotes that haven't surfaced recently, at random.
    select q.id into v_id
    from public.verum_quotes q
    where q.score >= p_core_threshold
      and (q.last_seen_at is null
           or q.last_seen_at < now() - make_interval(days => p_avoid_days))
    order by random()
    limit 1;

    -- Small pool: fall back to the least-recently-seen core quote.
    if v_id is null then
      select q.id into v_id
      from public.verum_quotes q
      where q.score >= p_core_threshold
      order by coalesce(q.last_seen_at, 'epoch'::timestamptz), random()
      limit 1;
    end if;

    -- No core quotes at all: any quote beats an empty reward.
    if v_id is null then
      select q.id into v_id
      from public.verum_quotes q
      order by coalesce(q.last_seen_at, 'epoch'::timestamptz), random()
      limit 1;
    end if;

    if v_id is null then
      return; -- empty pool: no pick today
    end if;

    insert into public.verum_quotes_daily_pick (day, quote_id)
    values (p_day, v_id)
    on conflict (day) do nothing;

    -- A concurrent caller may have recorded first; honor the stored pick.
    select quote_id into v_id
    from public.verum_quotes_daily_pick
    where day = p_day;

    update public.verum_quotes set last_seen_at = now() where id = v_id;
  end if;

  return query
    select * from public.verum_quotes q where q.id = v_id;
end;
$$;
